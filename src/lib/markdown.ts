import type { Evidence, Guide, Scenario } from "./schema";
import { assess, formatRange, TIERS } from "./rubric";

const badge: Record<Evidence["status"], string> = { tested: "✅ tested", documented: "📄 documented", unverified: "❓ unverified" };
const actor = { agent: "🤖 Agent", human: "👤 You", both: "🤝 Agent drafts, you submit" } as const;

function cite(e: Evidence, g: Guide): string {
  const refs = e.sourceIds.map((id) => g.sources.findIndex((s) => s.id === id) + 1).filter((n) => n > 0);
  return `_${badge[e.status]}${refs.length ? ` [${refs.join(", ")}]` : ""}${e.note && e.status !== "documented" ? ` — ${e.note}` : ""}_`;
}

function scenarioMd(s: Scenario, g: Guide): string {
  const a = assess(s.factors);
  const t = s.timeline;
  const out = [
    `## Scenario: ${s.label}`,
    "",
    s.description,
    "",
    `**Difficulty:** ${TIERS[a.tier].label} (tier ${a.tier}/4). ${a.reasons.join("; ")}.`,
    "",
    `- **First working connection:** ${formatRange(t.firstConnection.handsOnMinutes, "minutes")} hands-on. ${t.firstConnection.note}`,
    `- **Production-ready:** ${formatRange(t.production.handsOnHours, "hours")} hands-on${t.production.waitDays ? ` + ${formatRange(t.production.waitDays, "days")} waiting on the provider` : ", no provider wait"}. ${t.production.note}`,
    `- ${cite(t.evidence, g)}`,
    "",
  ];
  if (s.scopes.length) {
    out.push("**Scopes:**", "", ...s.scopes.map((sc) => `- \`${sc.name}\` (${sc.sensitivity}) — ${sc.purpose}`), "");
  }
  out.push("### Steps", "");
  s.steps.forEach((st, i) => {
    out.push(`${i + 1}. **${st.title}** — ${actor[st.actor]}${st.estMinutes ? ` · ~${st.estMinutes} min` : ""}`);
    out.push(`   ${st.detail}`);
    if (st.agentCan) out.push(`   - Agent can: ${st.agentCan}`);
    if (st.humanMust) out.push(`   - You must: ${st.humanMust}`);
    st.values.forEach((v) => out.push(`   - ${v.label}: \`${v.value}\``));
    st.links.forEach((l) => out.push(`   - [${l.label}](${l.url})`));
    out.push(`   - ${cite(st.evidence, g)}`);
  });
  if (s.blockers.length) {
    out.push("", "### If you get stuck", "");
    s.blockers.forEach((b) => out.push(`- **${b.title}.** You see: ${b.symptom} → ${b.whatToDo} ${cite(b.evidence, g)}`));
  }
  return out.join("\n");
}

export function guideToMarkdown(g: Guide, scenarioId?: string): string {
  const scenarios = scenarioId ? g.scenarios.filter((s) => s.id === scenarioId) : g.scenarios;
  const parts = [
    `# ${g.app.name}: OAuth app setup & approval guide`,
    "",
    `> ${g.summary}`,
    "",
    `_${g.origin === "curated" ? "Curated library guide" : "Generated by the research agent"} · last verified ${g.lastVerified} · [developer portal](${g.app.developerPortalUrl}) · [docs](${g.app.docsUrl})_`,
    "",
    "## Do you need your own OAuth app?",
    "",
    `- Composio-managed app available: **${g.composio.managedAppAvailable.value === null ? "unknown" : g.composio.managedAppAvailable.value ? "yes" : "no"}**`,
    `- ${g.composio.whenYouNeedYourOwn}`,
    g.composio.redirectUri.value ? `- Redirect URI to register: \`${g.composio.redirectUri.value}\`` : "",
    "",
    ...scenarios.map((s) => scenarioMd(s, g) + "\n"),
  ];
  if (g.artifacts.length) parts.push("## Drafts the agent prepared", "", ...g.artifacts.map((a) => `### ${a.title}\n\n${a.content}\n`));
  if (g.openQuestions.length) parts.push("## Still uncertain", "", ...g.openQuestions.map((q) => `- ${q}`), "");
  parts.push("## Sources", "", ...g.sources.map((s, i) => `${i + 1}. [${s.title}](${s.url}) (${s.kind}, accessed ${s.accessed})`), "");
  return parts.filter((p) => p !== "").join("\n").replace(/\n(#+ )/g, "\n\n$1");
}
